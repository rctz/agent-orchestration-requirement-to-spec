"""Converter registry — deterministic output-format layer.

Discovers every Converter subclass in this package's modules and serves
them by name. The gateway asks for a format by the string the caller sent
in options.output_format; an unknown name is a door-level rejection
(enum in input.schema.json), so get() here only sees approved names.

Hot-swap design (user requirement 2026-09-21):
- ADD an orchestrator    → drop <name>.py in this folder (implements
  Converter, decorated @register). Nothing else to edit: discovery is
  automatic at import; the schema enum, golden fixture and scaffolding
  are generated by `tools/make_adapter.py`.
- REMOVE/SWAP            → delete/replace the file and restart the
  gateway (registry caches per-process; the export CLI discovers fresh).
"""
from __future__ import annotations

import importlib
import pkgutil
from pathlib import Path

from .base import ConvertedFile, Converter, FieldGap  # noqa: F401 (re-export)

_REGISTRY: dict[str, type[Converter]] = {}


def _discover() -> None:
    """Import every sibling module once; each registers its Converter."""
    if _REGISTRY:
        return
    here = Path(__file__).parent
    for mod in pkgutil.iter_modules([str(here)]):
        if mod.name in ("base", "canonical"):
            continue
        importlib.import_module(f".{mod.name}", package=__package__)


def register(cls: type[Converter]) -> type[Converter]:
    """Decorator used by converter modules to enroll themselves."""
    name = cls.name
    if not name:
        raise ValueError(f"{cls.__name__} must define a non-empty 'name'")
    if name in _REGISTRY:
        raise ValueError(f"duplicate converter name: {name}")
    _REGISTRY[name] = cls
    return cls


def available() -> list[str]:
    _discover()
    return sorted(_REGISTRY)


def get(name: str) -> Converter:
    _discover()
    try:
        return _REGISTRY[name]()
    except KeyError:
        raise KeyError(
            f"unknown output_format {name!r} — available: {available()}. "
            f"(The door should have rejected this; if you see it, the "
            f"schema enum and registry are out of sync.)") from None
